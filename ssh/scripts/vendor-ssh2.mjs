// Bundles the "ssh2" library into src/vendor/ssh2.cjs for the Raycast build.
// ssh2 optionally loads two native modules (cpu-features, sshcrypto.node) inside try/catch and
// falls back to pure JavaScript without them. Raycast's bundler cannot handle native modules,
// so they are replaced by stubs that throw – exactly the "not installed" case ssh2 expects.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outfile = path.join(root, "src", "vendor", "ssh2.cjs");

const stubNative = {
  name: "stub-native",
  setup(b) {
    b.onResolve({ filter: /^cpu-features$|\.node$/ }, (args) => ({ path: args.path, namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({
      contents: "throw new Error('native module not available');",
      loader: "js",
    }));
  },
};

await build({
  entryPoints: [path.join(root, "node_modules", "ssh2", "lib", "index.js")],
  outfile,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  plugins: [stubNative],
  logLevel: "warning",
  legalComments: "inline",
});
fs.writeFileSync(
  path.join(root, "src", "vendor", "ssh2.d.cts"),
  '// Generated by scripts/vendor-ssh2.mjs – types come from @types/ssh2\nexport * from "ssh2";\n',
);
console.log(`vendored ssh2 → ${path.relative(root, outfile)}`);
